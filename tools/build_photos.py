#!/usr/bin/env python3
"""Inline src/photos/*.jpg into src/photos.js as base64 data URIs.

The ad has to render with no network at all — headless for the MP4 export, and
under a CSP that blocks external hosts for the preview page — so the photographs
travel inside the page like the fonts do.

Photos come in from the image generator at thumbnail size, so tools/grade_photo.sh
upscales and grades them before they land here. Anything missing simply does not
appear in PHOTOS, and sites.js falls back to a painted scene for that slot.
"""

import base64
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "photos"
OUT = ROOT / "src" / "photos.js"


def main() -> int:
    if not SRC.is_dir():
        print(f"no photo directory at {SRC}", file=sys.stderr)
        return 1

    files = sorted(p for p in SRC.iterdir() if p.suffix.lower() in {".jpg", ".jpeg", ".png"})
    if not files:
        print(f"no photos in {SRC}", file=sys.stderr)
        return 1

    entries = []
    total = 0
    for path in files:
        mime = "image/png" if path.suffix.lower() == ".png" else "image/jpeg"
        data = path.read_bytes()
        total += len(data)
        b64 = base64.b64encode(data).decode("ascii")
        entries.append(f"  {path.stem}: 'data:{mime};base64,{b64}',")
        print(f"  {path.name:28s} {len(data)/1024:7.1f} KB")

    OUT.write_text(
        "/* Generated by tools/build_photos.py -- do not edit by hand.\n"
        " * Photographs inlined as data URIs so the ad renders with no network. */\n\n"
        "const PHOTOS = {\n" + "\n".join(entries) + "\n};\n",
        encoding="utf-8",
    )
    print(f"\nwrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size/1024:.0f} KB from {total/1024:.0f} KB of photos)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
