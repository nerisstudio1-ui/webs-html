#!/usr/bin/env python3
"""Subset the display/body faces to a Spanish latin set and emit src/fonts.css
with every face inlined as a base64 woff2 data URI.

The ad has to survive with zero network access (it is rendered headless and
published under a CSP that blocks font CDNs), so a silent fallback to a system
grotesque is not an option -- the whole piece is built on the display face.
"""

import base64
import io
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = pathlib.Path("/mnt/skills/examples/canvas-design/canvas-fonts")
# Montserrat is vendored under src/fonts (SIL Open Font License).
LOCAL = ROOT / "src" / "fonts"
OUT = ROOT / "src" / "fonts.css"

# Latin + the Spanish diacritics, inverted marks, euro sign and the punctuation
# the mini-sites actually set.
GLYPHS = (
    "".join(chr(c) for c in range(0x20, 0x7F))
    + "áéíóúüñçÁÉÍÓÚÜÑÇ"
    + "¿¡€·—–…‘’“”→←↑↓★●○"
    + "ºª«»"
)

FACES = [
    # (file, css family, weight, style)
    ("Montserrat-500.ttf", "Montserrat", 500, "normal"),
    ("Montserrat-500Italic.ttf", "Montserrat", 500, "italic"),
    ("Montserrat-700.ttf", "Montserrat", 700, "normal"),
    ("Montserrat-700Italic.ttf", "Montserrat", 700, "italic"),
    ("Montserrat-900.ttf", "Montserrat", 900, "normal"),
    ("GeistMono-Regular.ttf", "Geist Mono", 400, "normal"),
    ("GeistMono-Bold.ttf", "Geist Mono", 700, "normal"),
    ("InstrumentSerif-Regular.ttf", "Instrument Serif", 400, "normal"),
    ("InstrumentSerif-Italic.ttf", "Instrument Serif", 400, "italic"),
    ("WorkSans-Regular.ttf", "Work Sans", 400, "normal"),
    ("WorkSans-Bold.ttf", "Work Sans", 700, "normal"),
    ("Outfit-Regular.ttf", "Outfit", 400, "normal"),
    ("Outfit-Bold.ttf", "Outfit", 700, "normal"),
    ("Lora-Regular.ttf", "Lora", 400, "normal"),
    ("Lora-Bold.ttf", "Lora", 700, "normal"),
    # Handwriting, for the script annotations the reference sites use.
    ("NothingYouCouldDo-Regular.ttf", "Hand", 400, "normal"),
    # A high-contrast display serif for the oversized headlines.
    ("Gloock-Regular.ttf", "Gloock", 400, "normal"),
    ("DMMono-Regular.ttf", "DM Mono", 400, "normal"),
]


def subset(path: pathlib.Path) -> bytes:
    from fontTools.subset import Subsetter, Options
    from fontTools.ttLib import TTFont

    font = TTFont(str(path))
    options = Options()
    options.flavor = "woff2"
    options.desubroutinize = True
    options.layout_features = ["kern", "liga", "calt"]
    options.notdef_outline = False
    options.drop_tables += ["DSIG"]
    subsetter = Subsetter(options=options)
    subsetter.populate(text=GLYPHS)
    subsetter.subset(font)

    buf = io.BytesIO()
    font.flavor = "woff2"
    font.save(buf)
    return buf.getvalue()


def main() -> int:
    if not SRC.is_dir():
        print(f"font source directory missing: {SRC}", file=sys.stderr)
        return 1

    blocks = [
        "/* Generated by tools/build_fonts.py -- do not edit by hand. */",
        "/* Faces subset to a Spanish latin set and inlined so the ad renders",
        "   identically offline, headless and under a font-blocking CSP. */",
        "",
    ]
    total = 0
    for filename, family, weight, style in FACES:
        path = LOCAL / filename
        if not path.exists():
            path = SRC / filename
        if not path.exists():
            print(f"  skip (missing): {filename}", file=sys.stderr)
            continue
        data = subset(path)
        total += len(data)
        b64 = base64.b64encode(data).decode("ascii")
        blocks.append(
            "@font-face{\n"
            f"  font-family:'{family}';\n"
            f"  font-weight:{weight};\n"
            f"  font-style:{style};\n"
            "  font-display:block;\n"
            f"  src:url(data:font/woff2;base64,{b64}) format('woff2');\n"
            "}"
        )
        print(f"  {filename:32s} -> {len(data)/1024:6.1f} KB")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(blocks) + "\n", encoding="utf-8")
    print(f"\nwrote {OUT} ({OUT.stat().st_size/1024:.0f} KB css, {total/1024:.0f} KB fonts)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
